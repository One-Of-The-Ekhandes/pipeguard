"""Generate docs/rules.md from the rule registry: python tools/gen_rules_doc.py"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeguard import rules  # noqa: E402,F401
from pipeguard.registry import RULES  # noqa: E402

TARGET_NAMES = {"github_actions": "GitHub Actions", "jenkins": "Jenkinsfile", "dockerfile": "Dockerfile",
                "terraform": "Terraform", "any": "Secrets (all files)"}


def render() -> str:
    out = ["# PipeGuard rules", "",
           f"{len(RULES)} rules. Generated by `tools/gen_rules_doc.py`; do not edit by hand.", "",
           "| ID | Severity | Applies to | Rule |", "|---|---|---|---|"]
    ordered = sorted(RULES.values(), key=lambda r: r.id)
    out += [f"| [{r.id}](#{r.id.lower()}) | {r.severity} | {TARGET_NAMES[r.target]} | {r.title} |" for r in ordered]
    for r in ordered:
        out += ["", f"## {r.id}", "", f"**{r.title}** · severity: {r.severity} · applies to: {TARGET_NAMES[r.target]}", "",
                f"**Why it matters:** {r.description}", "", f"**How to fix:** {r.fix}"]
        if r.references:
            out += ["", "**References:**"] + [f"- {ref}" for ref in r.references]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "rules.md").write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote docs/rules.md ({len(RULES)} rules)")
